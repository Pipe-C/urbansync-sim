"""The declarative base every ORM model inherits from.

Kept apart from the session factory because Alembic needs the metadata but must
not import an engine: a migration is a description of the schema, and building a
connection pool in order to write one is how a migration ends up needing the
database it is about to create.
"""

from datetime import UTC, datetime
from typing import Any

from sqlalchemy import DateTime, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column
from sqlalchemy.types import TypeDecorator


class Base(DeclarativeBase):
    """Declarative base for all models."""


class UTCDateTime(TypeDecorator):
    """`TIMESTAMP WITH TIME ZONE` that is timezone-aware in Python, on any backend.

    Postgres keeps the offset and returns an aware datetime. SQLite has no
    timezone type: it stores the wall clock and returns a *naive* one. Both are
    the same instant, but the code around them cares about the difference — the
    session check compares `expires_at <= now`, and `expiresAt` must carry an
    offset or the browser parses it as local time and expires the session hours
    early. Rather than guard every comparison and every serialisation, the
    normalisation happens here, once, at the boundary.

    The stored instant is always UTC, so a naive value coming back is a UTC value
    that lost its label, and re-attaching UTC is correct rather than a guess.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect: Any) -> datetime | None:
        if value is None:
            return None
        if value.tzinfo is None:
            value = value.replace(tzinfo=UTC)
        return value.astimezone(UTC)

    def process_result_value(self, value: datetime | None, dialect: Any) -> datetime | None:
        if value is None:
            return None
        if value.tzinfo is None:
            return value.replace(tzinfo=UTC)
        return value.astimezone(UTC)


class TimestampMixin:
    """`created_at` / `updated_at`, server-side.

    The timestamps are generated by the database (`func.now()`) rather than by
    Python, so rows inserted by a migration or a seed script carry the same
    honest clock as rows inserted by the API — there is no second definition of
    "now" to drift.
    """

    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime, server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime,
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
